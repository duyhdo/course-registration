CREATE TABLE dbo.TAIKHOAN (
    TaiKhoanId BIGINT IDENTITY(1,1) NOT NULL,
    TenDangNhap VARCHAR(50) NOT NULL,
    MatKhauHash VARCHAR(255) NOT NULL,
    VaiTro VARCHAR(20) NOT NULL,
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_TAIKHOAN_TrangThai DEFAULT ('ACTIVE'),
    NgayTao DATETIME2 NOT NULL CONSTRAINT DF_TAIKHOAN_NgayTao DEFAULT (SYSDATETIME()),
    NgayCapNhat DATETIME2 NULL,
    CONSTRAINT PK_TAIKHOAN PRIMARY KEY (TaiKhoanId)
);

CREATE TABLE dbo.KHOA (
    MaKhoa VARCHAR(10) NOT NULL,
    TenKhoa NVARCHAR(100) NOT NULL,
    MoTa NVARCHAR(255) NULL,
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_KHOA_TrangThai DEFAULT ('ACTIVE'),
    CONSTRAINT PK_KHOA PRIMARY KEY (MaKhoa)
);

CREATE TABLE dbo.SINHVIEN (
    MaSV VARCHAR(20) NOT NULL,
    TaiKhoanId BIGINT NULL,
    MaKhoa VARCHAR(10) NOT NULL,
    HoTen NVARCHAR(100) NOT NULL,
    NgaySinh DATE NULL,
    GioiTinh NVARCHAR(10) NULL,
    Email VARCHAR(100) NOT NULL,
    SoDienThoai VARCHAR(20) NULL,
    DiaChi NVARCHAR(255) NULL,
    KhoaHoc VARCHAR(20) NULL,
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_SINHVIEN_TrangThai DEFAULT ('ACTIVE'),
    CONSTRAINT PK_SINHVIEN PRIMARY KEY (MaSV),
    CONSTRAINT FK_SINHVIEN_TAIKHOAN FOREIGN KEY (TaiKhoanId) REFERENCES dbo.TAIKHOAN (TaiKhoanId),
    CONSTRAINT FK_SINHVIEN_KHOA FOREIGN KEY (MaKhoa) REFERENCES dbo.KHOA (MaKhoa)
);

CREATE TABLE dbo.GIANGVIEN (
    MaGV VARCHAR(20) NOT NULL,
    MaKhoa VARCHAR(10) NOT NULL,
    HoTen NVARCHAR(100) NOT NULL,
    Email VARCHAR(100) NULL,
    SoDienThoai VARCHAR(20) NULL,
    HocVi NVARCHAR(50) NULL,
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_GIANGVIEN_TrangThai DEFAULT ('ACTIVE'),
    CONSTRAINT PK_GIANGVIEN PRIMARY KEY (MaGV),
    CONSTRAINT FK_GIANGVIEN_KHOA FOREIGN KEY (MaKhoa) REFERENCES dbo.KHOA (MaKhoa)
);

CREATE TABLE dbo.MONHOC (
    MaMonHoc VARCHAR(20) NOT NULL,
    MaKhoa VARCHAR(10) NOT NULL,
    TenMonHoc NVARCHAR(100) NOT NULL,
    SoTinChi INT NOT NULL,
    SoTietLyThuyet INT NULL,
    SoTietThucHanh INT NULL,
    MoTa NVARCHAR(255) NULL,
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_MONHOC_TrangThai DEFAULT ('ACTIVE'),
    CONSTRAINT PK_MONHOC PRIMARY KEY (MaMonHoc),
    CONSTRAINT FK_MONHOC_KHOA FOREIGN KEY (MaKhoa) REFERENCES dbo.KHOA (MaKhoa)
);

CREATE TABLE dbo.HOCKY (
    MaHocKy VARCHAR(20) NOT NULL,
    TenHocKy NVARCHAR(50) NOT NULL,
    NamHoc VARCHAR(20) NOT NULL,
    NgayBatDau DATE NULL,
    NgayKetThuc DATE NULL,
    NgayMoDangKy DATETIME2 NULL,
    NgayDongDangKy DATETIME2 NULL,
    TinChiToiThieu INT NULL,
    TinChiToiDa INT NULL,
    CONSTRAINT PK_HOCKY PRIMARY KEY (MaHocKy)
);

CREATE TABLE dbo.LOPHOCPHAN (
    MaLopHocPhan VARCHAR(20) NOT NULL,
    MaMonHoc VARCHAR(20) NOT NULL,
    MaGV VARCHAR(20) NULL,
    MaHocKy VARCHAR(20) NOT NULL,
    PhongHoc NVARCHAR(50) NULL,
    ThuHoc INT NULL,
    TietBatDau INT NULL,
    TietKetThuc INT NULL,
    SiSoToiDa INT NOT NULL,
    SiSoHienTai INT NOT NULL CONSTRAINT DF_LOPHOCPHAN_SiSoHienTai DEFAULT ((0)),
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_LOPHOCPHAN_TrangThai DEFAULT ('DRAFT'),
    CONSTRAINT PK_LOPHOCPHAN PRIMARY KEY (MaLopHocPhan),
    CONSTRAINT FK_LOPHOCPHAN_MONHOC FOREIGN KEY (MaMonHoc) REFERENCES dbo.MONHOC (MaMonHoc),
    CONSTRAINT FK_LOPHOCPHAN_GIANGVIEN FOREIGN KEY (MaGV) REFERENCES dbo.GIANGVIEN (MaGV),
    CONSTRAINT FK_LOPHOCPHAN_HOCKY FOREIGN KEY (MaHocKy) REFERENCES dbo.HOCKY (MaHocKy)
);

CREATE TABLE dbo.DANGKYHOCPHAN (
    MaDangKy BIGINT IDENTITY(1,1) NOT NULL,
    MaSV VARCHAR(20) NOT NULL,
    MaLopHocPhan VARCHAR(20) NOT NULL,
    NgayDangKy DATETIME2 NOT NULL CONSTRAINT DF_DANGKYHOCPHAN_NgayDangKy DEFAULT (SYSDATETIME()),
    NgayHuy DATETIME2 NULL,
    TrangThai VARCHAR(20) NOT NULL CONSTRAINT DF_DANGKYHOCPHAN_TrangThai DEFAULT ('REGISTERED'),
    CONSTRAINT PK_DANGKYHOCPHAN PRIMARY KEY (MaDangKy),
    CONSTRAINT FK_DANGKYHOCPHAN_SINHVIEN FOREIGN KEY (MaSV) REFERENCES dbo.SINHVIEN (MaSV),
    CONSTRAINT FK_DANGKYHOCPHAN_LOPHOCPHAN FOREIGN KEY (MaLopHocPhan) REFERENCES dbo.LOPHOCPHAN (MaLopHocPhan)
);
